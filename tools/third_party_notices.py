#!/usr/bin/env python3
"""
Write THIRD_PARTY_NOTICES.txt: the license of every package bundled in the exe.

The package list comes from requirements/runtime-lock.txt, minus the modules the
PyInstaller spec excludes (NOT_BUNDLED). License texts are read from each
installed package's .dist-info, so run this from a venv that has the runtime
lock installed (make install / tasks.bat install). packaging/WindowsAutoclicker.spec
runs it on every build, so the notices always match what is bundled.

Usage:
  python tools/third_party_notices.py [OUTPUT]   # default build/THIRD_PARTY_NOTICES.txt
"""

from __future__ import annotations

import importlib.metadata as metadata
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK_FILE = ROOT / "requirements/runtime-lock.txt"
NOTICES_FILE = ROOT / "build" / "THIRD_PARTY_NOTICES.txt"

# pyautogui imports these optionally and the app never uses them; the spec
# excludes them (mouseinfo and pymsgbox are GPLv3+) (#153). Keep in sync with
# packaging/WindowsAutoclicker.spec (tests/test_third_party_notices.py checks).
NOT_BUNDLED = frozenset({"mouseinfo", "pymsgbox", "pyperclip"})

# Where the LGPL-licensed source can be obtained (LGPLv3 section 4).
SOURCE_OFFERS = {
    "pystray": "Source code: https://github.com/moses-palmer/pystray (the exact "
    "version above is on PyPI: https://pypi.org/project/pystray/).",
}

HEADER = """\
Third-party software in WindowsAutoclicker.exe
==============================================

Windows Autoclicker is licensed under CC BY-NC 4.0 (see LICENSE). The
executable also contains the software below, each under its own license.

- Python and its standard library: Python Software Foundation License
  (https://docs.python.org/3/license.html).
- Tcl/Tk: BSD-style license (https://www.tcl.tk/software/tcltk/license.html).
- PyInstaller bootloader: GPL 2.0 with an exception that allows distributing
  bundled applications under any license (https://pyinstaller.org/en/stable/license.html).

This file is generated by tools/third_party_notices.py from requirements/runtime-lock.txt.
"""

_LOCK_LINE = re.compile(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)")
_LICENSE_NAME = re.compile(r"(^|/)(LICEN[CS]E|COPYING|NOTICE|AUTHORS)[^/]*$", re.IGNORECASE)


def locked_packages(lock_text: str) -> list[tuple[str, str]]:
    """``(name, version)`` for each pin in the lock, excluding NOT_BUNDLED."""
    pins = []
    for line in lock_text.splitlines():
        match = _LOCK_LINE.match(line.strip())
        if match and match.group(1).lower() not in NOT_BUNDLED:
            pins.append((match.group(1), match.group(2)))
    return sorted(pins, key=lambda pin: pin[0].lower())


def _license_name(meta: metadata.PackageMetadata) -> str:
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [
        c.split("::")[-1].strip()
        for c in meta.get_all("Classifier") or []
        if c.startswith("License ::")
    ]
    if classifiers:
        return ", ".join(classifiers)
    first_line = (meta.get("License") or "").strip().splitlines()
    return first_line[0] if first_line else "see the license text below"


def _homepage(meta: metadata.PackageMetadata) -> str:
    if meta.get("Home-page"):
        return str(meta["Home-page"])
    for entry in meta.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        if label.strip().lower() in ("homepage", "source", "repository"):
            return url.strip()
    return f"https://pypi.org/project/{meta['Name']}/"


def _license_texts(dist: metadata.Distribution) -> list[tuple[str, str]]:
    """License files shipped in the package's .dist-info, as ``(path, text)``."""
    texts = []
    for file in dist.files or []:
        path = str(file).replace("\\", "/")
        if ".dist-info/" in path and _LICENSE_NAME.search(path):
            texts.append((path.split(".dist-info/", 1)[1], file.read_text("utf-8").strip()))
    if not texts:
        license_field = (dist.metadata.get("License") or "").strip()
        if "\n" in license_field:  # a full license text, not just a name
            texts.append(("License (from package metadata)", license_field))
    return sorted(texts)


def package_section(name: str, version: str) -> str:
    dist = metadata.distribution(name)
    installed = dist.version
    if installed != version:
        raise SystemExit(
            f"{name} {installed} is installed but the lock pins {version}; "
            "install requirements/runtime-lock.txt first"
        )
    meta = dist.metadata
    lines = [
        "-" * 78,
        f"{meta['Name']} {version}",
        f"License: {_license_name(meta)}",
        f"Homepage: {_homepage(meta)}",
    ]
    if name.lower() in SOURCE_OFFERS:
        lines.append(SOURCE_OFFERS[name.lower()])
    for path, text in _license_texts(dist):
        lines += ["", f"[{path}]", "", text]
    return "\n".join(lines)


def render(lock_text: str) -> str:
    sections = [package_section(name, version) for name, version in locked_packages(lock_text)]
    text = HEADER + "\n" + "\n\n".join(sections)
    return "\n".join(line.rstrip() for line in text.splitlines()) + "\n"


def write_notices(path: Path = NOTICES_FILE) -> Path:
    """Render the notices from the runtime lock into ``path``."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(LOCK_FILE.read_text("utf-8")), "utf-8", newline="\n")
    return path


def main(argv: list[str]) -> int:
    path = write_notices(Path(argv[0]) if argv else NOTICES_FILE)
    print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
